#!/usr/bin/env python3
"""Generate and run the Lean-scheduled CBD tier under hard resource limits."""

from __future__ import annotations

import argparse
import importlib.util
import os
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
SEA = ROOT.parent / "sea-of-verifiables"
VIRGIL = ROOT.parent / "virgil"
GENERATED = ROOT / "generated"
TIER = ROOT / "tiers/lean_interpreter"
LOCK = "/tmp/sea-scheduler-lean.lock"
LIMIT = ["flock", LOCK, "prlimit", "--as=4294967296", "--cpu=120", "--",
         "timeout", "--kill-after=5s", "120s"]


def run(command, *, cwd=ROOT, check=True):
    result = subprocess.run(
        [*LIMIT, *map(str, command)], cwd=cwd, text=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        env=dict(os.environ, LEAN_NUM_THREADS="4"),
    )
    if check and result.returncode:
        raise RuntimeError(f"Command failed ({result.returncode}): {' '.join(map(str, command))}\n"
                           + result.stdout[-16000:] + result.stderr[-16000:])
    return result


def sources(pattern):
    return sorted(ROOT.glob(pattern))


def shared_sources():
    return [*sorted((VIRGIL / "lib/util").glob("*.v3")),
            *sources("wizard-engine/src/engine/*.v3"),
            ROOT / "wizard-engine/src/engine/continuation/BoxedContinuation.v3",
            *sources("wizard-engine/src/util/*.v3")]


def generator_sources():
    return [*shared_sources(),
            *[p for p in sources("common/**/*.v3") if p.name != "PartitionTest.v3"],
            TIER / "Specialize.v3", TIER / "Emit.v3", TIER / "LeanInterpreterGen.v3"]


def interpret(files, args=()):
    result = run([VIRGIL / "bin/current/x86-64-linux/Aeneas", "-O2", "-run",
                  "-fun-exprs", "-simple-bodies", *files, *args])
    if result.stderr:
        # Aeneas's -run evaluator reports runtime errors without a failing exit code.
        if any(line.startswith("!") for line in result.stderr.splitlines()):
            raise RuntimeError(result.stdout + result.stderr)
        print(result.stderr, file=sys.stderr, end="")
    return result.stdout


def build_sea():
    cached = run(["lake", "--no-build", "build", "sea"], cwd=SEA, check=False)
    if cached.returncode == 0:
        return
    if cached.returncode != 3:
        raise RuntimeError(cached.stdout + cached.stderr)
    # Dependency order avoids Lake launching independent compiler processes.
    spec = importlib.util.spec_from_file_location("sea_test_build", SEA / "scripts/test.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for name in module.modules_in_order(("MainCLI",)):
        run(["lake", "build", f"+{name}:o"], cwd=SEA)
    run(["lake", "build", "sea"], cwd=SEA)


def write_checked(path, text, prefix):
    if not text.startswith(prefix):
        raise RuntimeError(f"Invalid generator output for {path.name}:\n{text[-16000:]}")
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text)
    temporary.replace(path)


def generate(opcodes=()):
    build_sea()
    GENERATED.mkdir(exist_ok=True)
    print("Preparing CBD Sea graphs...", flush=True)
    request = interpret(generator_sources(), ["prepare", *opcodes])
    request_path = GENERATED / "LeanInterpreter.request.sexp"
    response_path = GENERATED / "LeanInterpreter.schedule.sexp"
    write_checked(request_path, request, "(sea-exchange 1")
    print("Rewriting and scheduling with Lean...", flush=True)
    run([SEA / ".lake/build/bin/sea", "schedule-exchange", request_path,
         "--output", response_path])
    print("Emitting Virgil from the scheduled CFG...", flush=True)
    code = interpret(generator_sources(), ["emit", response_path])
    write_checked(GENERATED / "LeanInterpreter.v3", code, "// GENERATED BY LeanInterpreterGen")
    print("Generated generated/LeanInterpreter.v3", flush=True)


def runtime_sources():
    validator = GENERATED / "Validator.v3"
    if not validator.is_file():
        print("Generating the existing CBD validator...", flush=True)
        code = interpret([*shared_sources(),
                          *[p for p in sources("common/**/*.v3") if p.name != "PartitionTest.v3"],
                          ROOT / "tiers/validator/ValidatorGen.v3"])
        write_checked(validator, code, "// GENERATED BY ValidatorGen")
    return [*shared_sources(), *sources("wizard-engine/src/engine/v3/*.v3"),
            ROOT / "common/CBDTypes.v3", validator,
            GENERATED / "LeanInterpreter.v3", TIER / "LeanInterpreterMain.v3"]


def compile_wizard(reference=False):
    wizard = ROOT / "wizard-engine"
    if reference:
        files = shared_sources()
        for directory in ("native", "compiler", "x86-64"):
            files.extend(sources(f"wizard-engine/src/engine/{directory}/*.v3"))
        files.extend(sorted((VIRGIL / "lib/asm/x86-64").glob("*.v3")))
        files.append(wizard / "src/engine/x86-64/continuation/X86_64BoxedContinuation.v3")
    else:
        # The Lean tier uses Wizard's portable V3 runtime.
        files = [p for p in runtime_sources() if p.name != "LeanInterpreterMain.v3"]
        files.append(TIER / "LeanInterpreterTarget.v3")
    for directory in ("modules", "modules/wizeng", "modules/wave", "modules/wasi",
                      "modules/wali", "monitors"):
        files.extend(sources(f"wizard-engine/src/{directory}/*.v3"))
    files.extend([wizard / "src/WasmMode.v3", wizard / "src/wizeng.main.v3",
                  ROOT / "tests/PolyBenchMemoryMonitor.v3"])
    target = "x86-64-linux"
    files.extend(sources("wizard-engine/src/modules/wasi/x86-64-linux/*.v3"))
    files.extend(sources("wizard-engine/src/modules/wali/x86-64-linux/*.v3"))
    files.extend(sorted((VIRGIL / "lib/wasm-linux").glob("*.v3")))
    files.append(VIRGIL / "lib/x86-64-linux/SyscallLayouts.v3")
    binary = f"wizeng-{'reference' if reference else 'verified'}.{target}"
    result = run([VIRGIL / f"bin/v3c-{target}", "-O2", "-symbols",
                  "-heap-size=512m", "-stack-size=2m", "-fun-exprs", "-simple-bodies",
                  "-redef-field=FeatureDisable.unboxedConts=true",
                  f"-program-name={binary}", f"-output={wizard / 'bin'}/", *files])
    print(result.stdout, end="")
    print(f"Built wizard-engine/bin/{binary}", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    gen = commands.add_parser("generate")
    gen.add_argument("opcodes", nargs="*")
    compile_cmd = commands.add_parser("compile")
    wizard_choice = compile_cmd.add_mutually_exclusive_group()
    wizard_choice.add_argument("--wizard", action="store_true", help="build the Wizard CLI")
    wizard_choice.add_argument("--wizard-reference", action="store_true",
                               help="build Wizard's native fast interpreter with the memory monitor")
    execute = commands.add_parser("run")
    execute.add_argument("arguments", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    if args.command == "generate":
        generate(args.opcodes)
    elif args.command == "compile":
        if args.wizard or args.wizard_reference:
            compile_wizard(reference=args.wizard_reference)
            return
        result = run([VIRGIL / "bin/v3c-x86-64-linux", "-O2", "-fun-exprs",
                      "-simple-bodies", *runtime_sources()])
        print(result.stdout, end="")
    else:
        if not args.arguments:
            parser.error("run requires a Wasm file")
        print(interpret(runtime_sources(), args.arguments), end="")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
